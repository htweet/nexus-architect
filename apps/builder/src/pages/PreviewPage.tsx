// ─── Preview toolbar (floating) ───────────────────────────────────────────────

function PreviewToolbar({
  page,
  sizeKb,
  onClose,
}: {
  page: NexusPage;
  sizeKb: number;
  onClose: () => void;
}) {
  const [visible, setVisible] = useState(true);

  // Auto-hide after 3 seconds of no mouse movement
  useEffect(() => {
    let timer: ReturnType<typeof setTimeout>;
    const show = () => {
      setVisible(true);
      clearTimeout(timer);
      timer = setTimeout(() => setVisible(false), 3000);
    };
    show();
    window.addEventListener('mousemove', show);
    return () => {
      window.removeEventListener('mousemove', show);
      clearTimeout(timer);
    };
  }, []);

  return (
    <div
      style={{
        position:     'fixed',
        top:          '16px',
        left:         '50%',
        transform:    'translateX(-50%)',
        zIndex:       9999,
        display:      'flex',
        alignItems:   'center',
        gap:          '12px',
        padding:      '8px 16px',
        background:   'rgba(13,13,13,0.92)',
        border:       '1px solid rgba(255,255,255,0.1)',
        borderRadius: '40px',
        backdropFilter: 'blur(12px)',
        boxShadow:    '0 4px 24px rgba(0,0,0,0.5)',
        transition:   'opacity 0.3s',
        opacity:      visible ? 1 : 0,
        pointerEvents: visible ? 'auto' : 'none',
        fontFamily:   'system-ui, sans-serif',
        fontSize:     '12px',
        color:        '#9ca3af',
        whiteSpace:   'nowrap',
      }}
    >
      {/* Logo mark */}
      <div style={{ width: 20, height: 20, borderRadius: 5, background: '#10b981', display: 'flex', alignItems: 'center', justifyContent: 'center', flexShrink: 0 }}>
        <svg width="12" height="12" viewBox="0 0 16 16" fill="none">
          <path d="M3 13V3H5.2L10.8 9.8V3H13V13H10.8L5.2 6.2V13H3Z" fill="white" />
        </svg>
      </div>

      <span style={{ color: '#e5e7eb', fontWeight: 600 }}>{page.title}</span>

      <span style={{ color: '#4b5563' }}>|</span>

      <span>Draft preview</span>

      <span style={{ color: '#4b5563' }}>|</span>

      <span
        style={{
          padding:      '2px 8px',
          background:   'rgba(16,185,129,0.15)',
          border:       '1px solid rgba(16,185,129,0.3)',
          borderRadius: '12px',
          color:        '#10b981',
          fontSize:     '11px',
          fontWeight:   600,
        }}
      >
        {sizeKb.toFixed(1)} KB
      </span>

      <button
        onClick={onClose}
        style={{
          marginLeft:   '4px',
          padding:      '4px 12px',
          background:   'rgba(255,255,255,0.07)',
          border:       '1px solid rgba(255,255,255,0.1)',
          borderRadius: '20px',
          color:        '#9ca3af',
          cursor:       'pointer',
          fontSize:     '12px',
          transition:   'background 0.15s',
        }}
        onMouseEnter={(e) => { e.currentTarget.style.background = 'rgba(255,255,255,0.12)'; }}
        onMouseLeave={(e) => { e.currentTarget.style.background = 'rgba(255,255,255,0.07)'; }}
      >
        ✕ Close
      </button>
    </div>
  );
}

// ─── Main PreviewPage ─────────────────────────────────────────────────────────

export default function PreviewPage() {
  const [html,       setHtml]       = useState<string | null>(null);
  const [page,       setPage]       = useState<NexusPage | null>(null);
  const [sizeKb,     setSizeKb]     = useState(0);
  const [error,      setError]      = useState<string | null>(null);
  const [loading,    setLoading]    = useState(true);

  useEffect(() => {
    // Read page data from localStorage (written by TopBar before window.open)
    try {
      const raw = localStorage.getItem(PREVIEW_STORAGE_KEY);
      if (!raw) {
        setError(
          'No preview data found. Open the preview from the builder by clicking the Preview button.',
        );
        setLoading(false);
        return;
      }

      const pageData = JSON.parse(raw) as NexusPage;

      // Compile to static HTML using the same compiler as publish
      const result = compilePage(pageData);

      setPage(pageData);
      setHtml(result.html);
      setSizeKb(result.sizeKb);
      setLoading(false);
    } catch (err) {
      console.error('[PreviewPage] Failed to compile preview:', err);
      setError(
        err instanceof Error
          ? `Compilation error: ${err.message}`
          : 'Failed to compile preview. Check the browser console for details.',
      );
      setLoading(false);
    }
  }, []);

  if (loading) return <PreviewLoading />;
  if (error)   return <PreviewError message={error} />;
  if (!html || !page) return <PreviewError message="No content to preview." />;

  return (
    <div style={{ width: '100vw', height: '100vh', overflow: 'hidden', background: '#fff' }}>
      <PreviewToolbar
        page={page}
        sizeKb={sizeKb}
        onClose={() => window.close()}
      />
      <StaticHtmlPreview html={html} />
    </div>
  );
}

