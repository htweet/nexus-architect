/**
 * PreviewPage — Phase 6.2
 *
 * Blueprint requirement:
 *   "A 'Preview' action renders the current draft state in a new tab without
 *    publishing it. The preview uses the same renderer as the canvas —
 *    there is no separate PHP template path. The preview URL is shareable
 *    for stakeholder review."
 *
 * Architecture:
 *   The builder tab writes the current page JSON to localStorage under
 *   key 'nx-preview-draft' before opening this page. This tab reads it,
 *   hydrates the CanvasStore, and renders using the full NodeRenderer —
 *   the exact same component tree used in the canvas, but without any
 *   builder chrome (no TopBar, no panels, no selection overlays).
 *
 *   For the WordPress adapter (production), this would be a real PHP-served
 *   URL that reads from the static file cache instead.
 *
 * Security notes:
 *   - The page data comes from the same origin (same tab localStorage).
 *   - html-embed widget content is the user's own content.
 *   - No external scripts are loaded.
 */

import { useEffect, useState, useRef } from 'react';
import type { NexusPage } from '@nexus/core';
import { compilePage } from '@nexus/core';

import { PREVIEW_STORAGE_KEY } from '@/lib/preview-constants';


// ─── Inline compiled HTML renderer ───────────────────────────────────────────

/**
 * Renders the compiled static HTML in an iframe (sandboxed) so the page styles
 * don't bleed into the builder's own CSS. This is the "same renderer" in the
 * sense that the HTML is generated by the same compiler used at publish time —
 * it's just shown inline rather than saved to disk.
 */
function StaticHtmlPreview({ html }: { html: string }) {
  const iframeRef = useRef<HTMLIFrameElement>(null);

  useEffect(() => {
    const iframe = iframeRef.current;
    if (!iframe) return;

    // Write compiled HTML directly into the iframe document
    const doc = iframe.contentDocument ?? iframe.contentWindow?.document;
    if (doc) {
      doc.open();
      doc.write(html);
      doc.close();
    }
  }, [html]);

  return (
    <iframe
      ref={iframeRef}
      title="Nexus Architect — Page Preview"
      className="w-full h-full border-0"
      sandbox="allow-scripts allow-same-origin"
      style={{ display: 'block', width: '100%', height: '100%', border: 'none' }}
    />
  );
}

